def _e(value: object) -> str:
    return html.escape("-" if value is None or value == "" else str(value))


def _script_json(value: object) -> str:
    """JSON safe to inline in a <script> block."""
    return json.dumps(value).replace("</", "<\\/")


def _variant_panel(result: PipelineResult) -> str:
    a = result.annotation
    if a is None:
        return ""
    rows = [
        ("Variant", result.query),
        ("Gene", f"{a.gene_symbol or '-'} ({a.gene_id or '-'})"),
        ("Consequence", a.most_severe_consequence),
        ("Transcript", a.transcript_id),
    ]
    if a.protein_position:
        rows.append(("Protein change", f"{a.amino_acids or '?'} at residue {a.protein_position}"))
    if a.rsid:
        rows.append(("dbSNP", a.rsid))
    if a.clinvar_significance:
        rows.append(("ClinVar", ", ".join(s.replace("_", " ") for s in a.clinvar_significance)))
    if a.clinvar_somatic:
        rows.append(("ClinVar somatic", a.clinvar_somatic))
    if a.gnomad_af is not None:
        rows.append(("gnomAD AF", f"{a.gnomad_af:.3g}"))
    body = "".join(f"<dt>{_e(k)}</dt><dd>{_e(v)}</dd>" for k, v in rows)
    return f'<div class="panel"><h2>Variant</h2><dl>{body}</dl></div>'


def scorer_family(scorer: str) -> str:
    """'GeneMaskLFCScorer(DIFF_MEAN)' -> 'GeneMaskLFC'."""
    return scorer.split("(", 1)[0].removesuffix("Scorer")


def _scores_panel(result: PipelineResult, limit: int = 10) -> str:
    results = [vs for vs in result.variant_scores if vs.effects()]
    if not results:
        return ""
    # Rank scorers by their strongest effect in any condition.
    best: dict[tuple[str, str], float] = {}
    for vs in results:
        for s in vs.effects():
            key = (s.output_type, s.scorer)
            best[key] = max(best.get(key, 0.0), s.max_abs_score)
    top = sorted(best, key=best.__getitem__, reverse=True)[:limit]
    lookup = {(vs.label, s.output_type, s.scorer): s for vs in results for s in vs.effects()}

    head = "".join(f'<th class="num">{_e(vs.label)}</th>' for vs in results)
    body = ""
    for otype, scorer in top:
        cells = ""
        for vs in results:
            s = lookup.get((vs.label, otype, scorer))
            cells += f'<td class="num">{f"{s.top_score:+.4f}" if s else "-"}</td>'
        body += (
            f'<tr><td title="{_e(scorer)}">{_e(otype)} '
            f'<span class="scorer">{_e(scorer_family(scorer))}</span></td>{cells}</tr>'
        )
    conditions = ", ".join(vs.condition for vs in results)
    return (
        '<div class="panel"><h2>AlphaGenome effects</h2>'
        f'<p class="sub" style="margin:0 0 8px">{_e(conditions)}. Strongest effect score '
        "per output type; compare values within a row only.</p>"
        f'<div class="table-wrap"><table><thead><tr><th>Output</th>{head}</tr></thead>'
        f"<tbody>{body}</tbody></table></div></div>"
    )


def render_structure_html(result: PipelineResult, structure: StructureResult) -> str:
    entry = structure.entry
    pdb_text = Path(structure.structure_path).read_text()
    residue = structure.residue if structure.residue_plddt is not None else None

    residue_row = ""
    focus_button = ""
    if residue is not None:
        residue_row = (
            f'<dt>Residue {residue}</dt><dd class="hl">pLDDT {structure.residue_plddt:.1f} '
            f"({_e(structure.residue_confidence)})</dd>"
        )
        focus_button = f'<button id="btn-focus">Focus residue {residue}</button>'

    legend = "".join(
        f'<div><span style="background:{c}"></span>{_e(t)}</div>' for _, c, t in PLDDT_BANDS
    )
    gene = entry.gene or (result.annotation.gene_symbol if result.annotation else None)
    heading = f"{gene} · {result.query}" if gene and gene not in result.query else result.query

    return _TEMPLATE.format(
        title=_e(f"{gene or entry.uniprot_accession} structure"),
        heading=_e(heading),
        subheading=_e(f"{entry.description or ''} ({entry.organism or 'unknown organism'})"),
        entry_id=_e(entry.entry_id),
        accession=_e(entry.uniprot_accession),
        description=_e(entry.description),
        organism=_e(entry.organism),
        mean_plddt=_e(structure.mean_plddt),
        residue_row=residue_row,
        focus_button=focus_button,
        variant_panel=_variant_panel(result),
        scores_panel=_scores_panel(result),
        legend=legend,
        threedmol_url=THREEDMOL_URL,
        pdb_json=_script_json(pdb_text),
        residue_json=_script_json(residue),
        bands_json=_script_json([[cut, colour] for cut, colour, _ in PLDDT_BANDS]),
    )


def write_structure_html(result: PipelineResult, structure: StructureResult, path: Path) -> Path:
    if Path(structure.structure_path).suffix != ".pdb":
        raise ValueError("The HTML viewer embeds PDB files; fetch the structure with fmt='pdb'")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_structure_html(result, structure))
    return path
